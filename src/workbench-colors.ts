/** Ensure every value in a colour map is a normalised 8 digit hex string. */
function normalizeColorMap(colors: WorkbenchColors): WorkbenchColors {
  const normalized: WorkbenchColors = {};
  for (const [key, value] of Object.entries(colors)) {
    if (value === undefined) throw new Error(`colour key "${key}" has no value`);
    normalized[key] = normalizeHex(value);
  }
  return normalized;
}
